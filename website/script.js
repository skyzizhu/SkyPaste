const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.16 });

document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));

const heroShot = document.querySelector(".hero-shot");
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
let ticking = false;

function updateHeroMotion() {
  const progress = Math.min(window.scrollY / 620, 1);
  if (!heroShot) {
    ticking = false;
    return;
  }

  heroShot.style.transform = `translate3d(0, ${progress * 14}px, 0) scale(${1 - progress * 0.012})`;
  ticking = false;
}

if (!reduceMotion) {
  window.addEventListener("scroll", () => {
    if (!ticking) {
      window.requestAnimationFrame(updateHeroMotion);
      ticking = true;
    }
  }, { passive: true });
}

