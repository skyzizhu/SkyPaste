const languageNames = {
  "zh-Hans": "简体中文",
  "zh-Hant": "繁體中文",
  en: "English",
  ja: "日本語",
  ko: "한국어",
  fr: "Français"
};

const htmlLang = {
  "zh-Hans": "zh-CN",
  "zh-Hant": "zh-Hant",
  en: "en",
  ja: "ja",
  ko: "ko",
  fr: "fr"
};

const languageSelect = document.querySelector(".language-select");
const translatable = document.querySelectorAll("[data-i18n]");
const year = document.querySelector("#year");
const wechatPopover = document.querySelector("[data-wechat-popover]");
const wechatOpen = document.querySelector("[data-wechat-open]");
const wechatQrPlaceholder = document.querySelector(".wechat-qr-placeholder");
const wechatCard = document.querySelector(".wechat-card");
const supportedLanguages = Object.keys(copy);

function preferredLanguage() {
  const saved = localStorage.getItem("skypaste-site-language");
  if (supportedLanguages.includes(saved)) {
    return saved;
  }

  const browserLanguages = Array.isArray(navigator.languages) && navigator.languages.length > 0
    ? navigator.languages
    : [navigator.language || "zh-Hans"];

  for (const browserLanguage of browserLanguages) {
    if (browserLanguage.startsWith("zh-Hant") || browserLanguage.includes("TW") || browserLanguage.includes("HK")) {
      return "zh-Hant";
    }
    if (browserLanguage.startsWith("zh")) {
      return "zh-Hans";
    }

    const shortCode = browserLanguage.slice(0, 2);
    if (supportedLanguages.includes(shortCode)) {
      return shortCode;
    }
  }

  return "en";
}

function applyLanguage(language) {
  const nextLanguage = supportedLanguages.includes(language) ? language : "en";
  document.documentElement.lang = htmlLang[nextLanguage];
  document.title = nextLanguage === "zh-Hans" || nextLanguage === "zh-Hant"
    ? "SkyPaste - macOS 剪贴板管理器"
    : "SkyPaste - Clipboard Manager for macOS";

  translatable.forEach((element) => {
    const key = element.dataset.i18n;
    element.textContent = copy[nextLanguage][key];
  });

  languageSelect.value = nextLanguage;
  languageSelect.setAttribute("aria-label", languageNames[nextLanguage]);
  localStorage.setItem("skypaste-site-language", nextLanguage);
}

languageSelect.addEventListener("change", (event) => {
  applyLanguage(event.target.value);
});

function positionWechatPopover() {
  const buttonRect = wechatOpen.getBoundingClientRect();
  const cardWidth = wechatCard.offsetWidth || 300;
  const viewportPadding = 12;
  const idealLeft = buttonRect.left + buttonRect.width / 2;
  const minLeft = viewportPadding + cardWidth / 2;
  const maxLeft = window.innerWidth - viewportPadding - cardWidth / 2;
  const clampedLeft = Math.min(Math.max(idealLeft, minLeft), Math.max(minLeft, maxLeft));
  const pointerLeft = Math.min(
    Math.max(idealLeft - (clampedLeft - cardWidth / 2), 28),
    cardWidth - 28
  );
  wechatPopover.style.left = `${clampedLeft}px`;
  wechatPopover.style.top = `${buttonRect.top}px`;
  wechatCard.style.setProperty("--pointer-left", `${pointerLeft}px`);
}

function openWechatPopover() {
  positionWechatPopover();
  wechatPopover.classList.add("open");
  wechatPopover.setAttribute("aria-hidden", "false");
}

function closeWechatPopover() {
  wechatPopover.classList.remove("open");
  wechatPopover.setAttribute("aria-hidden", "true");
}

wechatOpen.addEventListener("click", (event) => {
  event.stopPropagation();
  if (wechatPopover.classList.contains("open")) {
    closeWechatPopover();
    return;
  }
  openWechatPopover();
});

wechatPopover.addEventListener("click", (event) => {
  event.stopPropagation();
});

window.addEventListener("click", () => {
  if (wechatPopover.classList.contains("open")) {
    closeWechatPopover();
  }
});

window.addEventListener("resize", () => {
  if (wechatPopover.classList.contains("open")) {
    positionWechatPopover();
  }
});

window.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && wechatPopover.classList.contains("open")) {
    closeWechatPopover();
  }
});

