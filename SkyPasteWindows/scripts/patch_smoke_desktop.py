#!/usr/bin/env python3
"""Replace workflow smoke section with desktop-capture + title echo."""
import sys

p = "/Users/skyzizhu/Desktop/SkyPaste/.github/workflows/windows-build.yml"
s = open(p, encoding="utf-8").read()

old = (
    '      - name: Smoke test (launch, alive check, per-window screenshots)' + chr(10)
    + '        shell: pwsh' + chr(10)
    + '        run: |' + chr(10)
    + '          foreach ($scenario in @("main", "settings", "statistics")) {' + chr(10)
    + '            $p = Start-Process -FilePath "publish/SkyPaste.exe" -ArgumentList "--uitesting:$scenario" -PassThru' + chr(10)
    + '            Start-Sleep -Seconds 20' + chr(10)
    + '            $alive = Get-Process -Id $p.Id -ErrorAction SilentlyContinue' + chr(10)
    + '            if (-not $alive) {' + chr(10)
    + '              Write-Error "SkyPaste.exe exited within 20s of launch (scenario: $scenario)"' + chr(10)
    + '              exit 1' + chr(10)
    + '            }' + chr(10)
    + '            Stop-Process -Id $p.Id -Force' + chr(10)
    + '            Start-Sleep -Seconds 2' + chr(10)
    + '          }' + chr(10)
    + chr(10)
    + '      - name: Upload smoke screenshots' + chr(10)
    + '        uses: actions/upload-artifact@v4' + chr(10)
    + '        with:' + chr(10)
    + '          name: smoke-${{ github.sha }}' + chr(10)
    + '          path: |' + chr(10)
    + '            SkyPasteWindows/publish/smoke-main.png' + chr(10)
    + '            SkyPasteWindows/publish/smoke-settings.png' + chr(10)
    + '            SkyPasteWindows/publish/smoke-statistics.png' + chr(10)
    + '          if-no-files-found: warn'
)

new = (
    '      - name: Smoke test (launch, alive check, desktop screenshots)' + chr(10)
    + '        shell: pwsh' + chr(10)
    + '        run: |' + chr(10)
    + '          Add-Type -AssemblyName System.Windows.Forms' + chr(10)
    + '          Add-Type -AssemblyName System.Drawing' + chr(10)
    + '          foreach ($scenario in @("main", "settings", "statistics")) {' + chr(10)
    + '            $p = Start-Process -FilePath "publish/SkyPaste.exe" -ArgumentList "--uitesting:$scenario" -PassThru' + chr(10)
    + '            Start-Sleep -Seconds 20' + chr(10)
    + '            $alive = Get-Process -Id $p.Id -ErrorAction SilentlyContinue' + chr(10)
    + '            if (-not $alive) {' + chr(10)
    + '              Write-Error "SkyPaste.exe exited within 20s of launch (scenario: $scenario)"' + chr(10)
    + '              exit 1' + chr(10)
    + '            }' + chr(10)
    + '            $title = (Get-Process -Id $p.Id).MainWindowTitle' + chr(10)
    + '            Write-Host "scenario=$scenario MainWindowTitle=\'$title\'"' + chr(10)
    + '            $bounds = [System.Windows.Forms.Screen]::PrimaryScreen.Bounds' + chr(10)
    + '            $bmp = New-Object System.Drawing.Bitmap $bounds.Width, $bounds.Height' + chr(10)
    + '            $graphics = [System.Drawing.Graphics]::FromImage($bmp)' + chr(10)
    + '            $graphics.CopyFromScreen($bounds.Location, [System.Drawing.Point]::Empty, $bounds.Size)' + chr(10)
    + '            $bmp.Save("$PWD/smoke-$scenario.png")' + chr(10)
    + '            $graphics.Dispose()' + chr(10)
    + '            $bmp.Dispose()' + chr(10)
    + '            Stop-Process -Id $p.Id -Force' + chr(10)
    + '            Start-Sleep -Seconds 2' + chr(10)
    + '          }' + chr(10)
    + chr(10)
    + '      - name: Upload smoke screenshots + UI logs' + chr(10)
    + '        uses: actions/upload-artifact@v4' + chr(10)
    + '        with:' + chr(10)
    + '          name: smoke-${{ github.sha }}' + chr(10)
    + '          path: |' + chr(10)
    + '            SkyPasteWindows/smoke-main.png' + chr(10)
    + '            SkyPasteWindows/smoke-settings.png' + chr(10)
    + '            SkyPasteWindows/smoke-statistics.png' + chr(10)
    + '            C:/Users/runneradmin/AppData/Roaming/SkyPaste/logs/' + chr(10)
    + '          if-no-files-found: warn'
)

if old not in s:
    print("ERROR: smoke section not found verbatim")
    idx = s.find("Smoke test")
    print(repr(s[idx - 20:idx + 120]))
    sys.exit(1)

s = s.replace(old, new, 1)
open(p, "w", encoding="utf-8").write(s)
print("OK: workflow smoke -> desktop capture")
